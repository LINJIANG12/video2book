def _normalize_type_token(text: str) -> str:
    """类型键/中文名的宽松归一：忽略空白、括号、斜杠与大小写差异。"""
    return re.sub(r"[\s（()）/\-—、,，]", "", str(text or "")).lower()


def _article_type_lookup() -> Dict[str, str]:
    """构造「键 / 中文全名 / 中文简称」到类型键的查表。"""
    table: Dict[str, str] = {}
    for key, meta in ARTICLE_PROMPT_TYPES.items():
        label = str(meta.get("label", ""))
        short = re.split(r"[（(]", label)[0].strip()
        for form in (key, label, short):
            token = _normalize_type_token(form)
            if token:
                table[token] = key
    return table


def _type_short_label(key: str) -> str:
    """取类型中文简称（去掉括号内的举例）。"""
    label = str(ARTICLE_PROMPT_TYPES.get(key, {}).get("label", key))
    return re.split(r"[（(]", label)[0].strip() or key


class ArticlePromptTypeError(ValueError):
    """长文提示词类型不符合任何已提供的预设：必须提示并终止任务（不猜、不降级）。"""

    def __init__(self, reason: str, type_key: str = ""):
        super().__init__(reason)
        self.reason = reason
        self.type_key = type_key
