def render_article_prompt_menu() -> str:
    """渲染提示词风格菜单（供 --article-type 选择，以及未命中时的终止提示）。"""
    lines = ["【长文提示词风格菜单（由用户确认后显式选择）】"]
    for idx, (key, meta) in enumerate(ARTICLE_PROMPT_TYPES.items(), 1):
        if meta.get("prompt"):
            state = "推荐" if meta.get("recommended") else "已提供提示词"
        else:
            state = "提示词未提供（命中即终止）"
        lines.append(f"  {idx}. {meta['label']}  [--article-type {key}]  —— {state}")
        for sig in meta.get("signals", []):
            lines.append(f"       适用信号：{sig}")
    lines.append("用法：python src/cli.py pipeline \"<链接>\" --all --article-type learning")
    return "\n".join(lines)


def resolve_article_prompt(type_key: str) -> Dict[str, str]:
    """解析长文写作提示词；不符合任何已提供预设时抛 ArticlePromptTypeError。"""
    raw = str(type_key or "").strip()
    if not raw:
        raise ArticlePromptTypeError(
            "未指定长文提示词风格（--article-type）。请确认使用哪一种后重跑，推荐「学习」。"
        )
    key = _article_type_lookup().get(_normalize_type_token(raw))
    if key is None:
        raise ArticlePromptTypeError(
            f"「{raw}」不是已登记的提示词风格（拼写有误，或本片根本不属于现有预设）", raw,
        )
    meta = ARTICLE_PROMPT_TYPES[key]
    if not meta.get("prompt"):
        _ready = "、".join(f"{_type_short_label(k)}（{k}）" for k in IMPLEMENTED_ARTICLE_TYPES)
        raise ArticlePromptTypeError(
            f"本片被判为「{_type_short_label(key)}」，但该类型的写作提示词尚未提供"
            f"（当前只提供：{_ready}），无法派发",
            key,
        )
    return {"key": key, "label": str(meta["label"]), "prompt": str(meta["prompt"])}
